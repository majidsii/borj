#!/usr/bin/env python3
"""Extracts the outlines of "Borj" from Vazirmatn (OFL) at a fixed weight into
latin_outline.py, so build.py stays dependency-free. Needs fonttools:
  python -m venv v && v/bin/pip install fonttools && v/bin/python extract_latin.py <font> [weight]
"""
import re
import sys
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

font = TTFont(sys.argv[1])
weight = float(sys.argv[2]) if len(sys.argv) > 2 else 800
font = instantiateVariableFont(font, {"wght": weight})
gs, cmap = font.getGlyphSet(), font.getBestCmap()
upm = font["head"].unitsPerEm
cap = font["OS/2"].sCapHeight
x, parts = 0, []
for ch in "Borj":
    name = cmap[ord(ch)]
    pen = SVGPathPen(gs)
    # flip y: font units grow upward; SVG grows downward. Baseline at y = cap.
    gs[name].draw(TransformPen(pen, (1, 0, 0, -1, x, cap)))
    parts.append(re.sub(r"-?\d+\.\d+", lambda m: f"{float(m.group()):.1f}".rstrip("0").rstrip("."), pen.getCommands()))
    x += gs[name].width
out = Path(__file__).with_name("latin_outline.py")
out.write_text(
    f'"""Generated by extract_latin.py from Vazirmatn wght={weight:g}. Units: font units, baseline y={cap}."""\n'
    f"CAP = {cap}\nADVANCE = {x}\nUPM = {upm}\nPATH = {''.join(parts)!r}\n",
    encoding="utf-8",
)
print(out, cap, x)
